/** 긴 단어가 먼저 바뀌도록 (举牌接机 → 피켓, 接机 → 픽업) */
const BY_LENGTH = [...PHRASES].sort((a, b) => b[0].length - a[0].length);

const CJK = /[㐀-鿿豈-﫿぀-ヿ]/;

/** 중국어·일본어가 섞인 글을 한국어로. 한자가 없으면 그대로 */
export function ko(s: string): string;
export function ko(s: string | null | undefined): string | null;
export function ko(s: string | null | undefined): string | null {
  if (s == null) return null;
  if (!CJK.test(s) && !/South Korea|Corea del Sur|Zuid-Korea/.test(s)) return s;
  let t = s;
  for (const [a, b] of BY_LENGTH) if (t.includes(a)) t = t.split(a).join(b);
  t = t
    .replace(/(\d)\s*[点點时時]\s*(\d{1,2})\s*分?/g, "$1시 $2분 ")
    .replace(/(\d)\s*[点點时時]/g, "$1시 ")
    .replace(/(\d)\s*分/g, "$1분 ")
    .replace(/(\d)\s*座/g, "$1인승")
    .replace(/[。]/g, ". ")
    .replace(/[，、]/g, ", ")
    .replace(/[（]/g, "(")
    .replace(/[）]/g, ")")
    .replace(/[～〜]/g, "~")
    .replace(/[㐀-鿿豈-﫿]/g, (c) => HANJA[c] ?? c);
  return t.replace(/\s+/g, " ").replace(/\s+([,.)~])/g, "$1").replace(/\(\s+/g, "(").trim();
}

/** 예약 행의 글자 칸들을 한국어로 (표시용 복사본) */
export function koBooking<
  T extends Partial<Record<"customer_name" | "pickup_place" | "dropoff_place" | "pickup_address" | "dropoff_address" | "memo" | "product_name" | "vehicle_class" | "trip_type", string | null>>,
>(b: T): T {
  const out = { ...b };
  for (const k of ["customer_name", "pickup_place", "dropoff_place", "pickup_address", "dropoff_address", "memo", "product_name", "vehicle_class", "trip_type"] as const) {
    if (typeof out[k] === "string") (out as Record<string, unknown>)[k] = ko(out[k] as string);
  }
  return out;
}
